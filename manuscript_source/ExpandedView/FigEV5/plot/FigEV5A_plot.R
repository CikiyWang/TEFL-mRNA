suppressPackageStartupMessages({
  library(data.table)
  library(ggplot2)
})

file_arg <- grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)
base_dir <- if (length(file_arg)) dirname(dirname(normalizePath(sub("^--file=", "", file_arg)))) else getwd()
output_dir <- file.path(base_dir, "output")

df <- fread(file.path(output_dir, "FigEV5A_source_data.tsv"), sep = "\t")
aa_order <- fread(file.path(output_dir, "FigEV5A_summary.tsv"), sep = "\t")$aa_var
df$aa_var <- factor(df$aa_var, levels = aa_order)

p <- ggplot(df, aes(x = aa_var, y = delta_score_high, fill = aa_var)) +
  geom_violin(alpha = 0.2, linewidth = 0.3) +
  geom_boxplot(width = 0.1, outlier.shape = ".", linewidth = 0.3) +
  geom_hline(yintercept = 0, linetype = "dashed") +
  theme_bw() +
  scale_fill_viridis_d(guide = "none") +
  labs(x = NULL, y = expression(pTE[ALT] - pTE[REF]), title = "Peptides generated by missense variants") +
  theme(aspect.ratio = 0.2,
        axis.text.y = element_text(size = 10, color = "black"),
        axis.text.x = element_text(size = 9, color = "black"),
        legend.title = element_text(size = 10, color = "black"),
        legend.text = element_text(size = 10, color = "black"),
        axis.title = element_text(size = 12, color = "black"),
        plot.title = element_text(lineheight = 20, color = "black", size = 13, hjust = 0.5, vjust = 0.5))

ggsave(file.path(output_dir, "FigEV5A.pdf"), p, width = 8.5, height = 4)
